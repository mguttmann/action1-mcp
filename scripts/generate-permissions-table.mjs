#!/usr/bin/env node
// Generate `docs/permissions.md`: the Action1 role permissions each API
// operation (and the tool that calls it) needs, taken from the
// permission tags in the pinned OpenAPI spec. Hand-written permission
// tables drifted from the spec before; this file is the only source.
//
//   node scripts/generate-permissions-table.mjs          write the file
//   node scripts/generate-permissions-table.mjs --check  exit 1 if stale
//
// tests/unit/permissionsTable.test.ts runs the same render and fails
// when the committed file differs.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseGeneratedManifest } from "./generated-manifest.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..");
export const SPEC_PATH = join(repoRoot, "src", "codegen", "spec", "openapi.json");
export const GENERATED_PATH = join(repoRoot, "src", "tools", "generated", "index.ts");
export const OUT_PATH = join(repoRoot, "docs", "permissions.md");

const METHODS = ["GET", "HEAD", "POST", "PUT", "PATCH", "DELETE"];
// Same marker the code generator reads (src/codegen/generate.ts).
const PERM_MARKER = /\*\*Requires(?: one of the following)? permissions?:[^*]*\*\*/i;
const NOT_STATED = "(not stated in spec)";

/** Permission tags of one operation description, in spec order. */
export function permissionsOf(description) {
  const m = (description ?? "").match(PERM_MARKER);
  if (!m) return { anyOf: false, perms: [] };
  return {
    anyOf: /one of the following/i.test(m[0]),
    perms: [...m[0].matchAll(/`([^`]+)`/g)].map((x) => x[1]),
  };
}

/** Map "METHOD path" -> tool name from the generated manifest and the skipped (curated) list. */
export function toolsByOperation(generatedSource) {
  const out = new Map();
  const { tools, skipped } = parseGeneratedManifest(generatedSource);
  for (const t of tools) out.set(`${t.method} ${t.path}`, t.name);
  for (const s of skipped) out.set(`${s.method} ${s.path}`, s.toolName);
  return out;
}

/** Render docs/permissions.md from the spec object and the generated index source. */
export function renderPermissionsDoc(spec, generatedSource) {
  const tools = toolsByOperation(generatedSource);
  const rows = [];
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const [methodLc, op] of Object.entries(item)) {
      const method = methodLc.toUpperCase();
      if (!METHODS.includes(method)) continue;
      if (path === "/oauth2/token") continue;
      const { anyOf, perms } = permissionsOf(op.description);
      rows.push({ method, path, tool: tools.get(`${method} ${path}`), anyOf, perms });
    }
  }
  rows.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));

  const byPerm = new Map();
  for (const r of rows) {
    for (const p of r.perms) {
      if (!byPerm.has(p)) byPerm.set(p, new Set());
      if (r.tool) byPerm.get(p).add(r.tool);
    }
  }
  const permNames = [...byPerm.keys()].sort();

  const cell = (r) => {
    if (r.perms.length === 0) return NOT_STATED;
    const list = r.perms.map((p) => `\`${p}\``).join(", ");
    return r.anyOf && r.perms.length > 1 ? `one of ${list}` : list;
  };

  const lines = [
    "<!-- AUTO-GENERATED by scripts/generate-permissions-table.mjs from the pinned OpenAPI spec. Do not edit by hand. -->",
    "",
    "# Action1 role permissions per tool",
    "",
    "Which permission the Action1 API credential's role needs for each API",
    "operation, taken from the permission tags in the pinned OpenAPI spec",
    "(`src/codegen/spec/openapi.json`). Regenerate with",
    "`node scripts/generate-permissions-table.mjs` after a spec update;",
    "`tests/unit/permissionsTable.test.ts` fails while this file is stale.",
    "",
    "For least privilege, grant the role only the permissions of the tools",
    "you use. A 403 from a tool usually means its permission is missing.",
    `Operations whose spec entry names no permission are marked ${NOT_STATED}.`,
    "Curated tools that call an operation without a generated tool of their",
    "own are not listed by name; their descriptions name the endpoint they use.",
    "",
    "## By permission",
    "",
    "| Permission | Tools |",
    "|---|---|",
    ...permNames.map((p) => {
      const t = [...byPerm.get(p)].sort().map((n) => `\`${n}\``);
      return `| \`${p}\` | ${t.length ? t.join(", ") : "-"} |`;
    }),
    "",
    "## By API operation",
    "",
    "| Method | Path | Tool | Permissions |",
    "|---|---|---|---|",
    ...rows.map(
      (r) => `| ${r.method} | \`${r.path}\` | ${r.tool ? `\`${r.tool}\`` : "-"} | ${cell(r)} |`,
    ),
    "",
  ];
  return lines.join("\n");
}

export function renderFromRepo() {
  const spec = JSON.parse(readFileSync(SPEC_PATH, "utf8"));
  return renderPermissionsDoc(spec, readFileSync(GENERATED_PATH, "utf8"));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const doc = renderFromRepo();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT_PATH, "utf8");
    } catch {
      // missing counts as stale
    }
    if (current !== doc) {
      console.error(`${OUT_PATH} is out of date. Run: node scripts/generate-permissions-table.mjs`);
      process.exit(1);
    }
    console.log(`${OUT_PATH} is up to date.`);
  } else {
    writeFileSync(OUT_PATH, doc, "utf8");
    console.log(`Wrote ${OUT_PATH}`);
  }
}
